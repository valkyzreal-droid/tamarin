#!/usr/bin/env python3
"""Turn tokens.json + tokens.dark.json into WPF resource dictionaries and a
visual preview. Standard library only. Re-run after any token change (including
the rebrand), then re-run contrast.py.

    python3 generate.py

Writes: src/Tamarin.App/Themes/{Colors.Light,Colors.Dark,Typography,Metrics}.xaml
        and tools/design/preview.html
"""
import html
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "src" / "Tamarin.App" / "Themes"
OUT.mkdir(exist_ok=True)

light = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
dark = json.loads((HERE / "tokens.dark.json").read_text(encoding="utf-8"))

NS = ('xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
      '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"')
NS_SYS = NS + '\n                    xmlns:sys="clr-namespace:System;assembly=mscorlib"'
WEIGHTS = {400: "Normal", 500: "Medium", 600: "SemiBold", 700: "Bold"}


def pascal(name):
    return "".join(p.capitalize() for p in name.split("-"))


def argb(hex_):
    return "#FF" + hex_.lstrip("#").upper()


def luminance(hex_):
    h = hex_.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255.0
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2]


def ratio(a, b):
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def colors_xaml(theme_name, colors):
    lines = ['<!-- Generated by generate.py from tokens. Do not edit by hand. -->',
             '<!-- Swap this dictionary at runtime and bind with DynamicResource so the theme changes live. -->',
             f'<ResourceDictionary {NS}>']
    for role, value in colors.items():
        key = pascal(role)
        lines.append(f'  <Color x:Key="Color.{key}">{argb(value)}</Color>')
    lines.append("")
    for role in colors:
        key = pascal(role)
        lines.append(f'  <SolidColorBrush x:Key="Brush.{key}" Color="{{StaticResource Color.{key}}}"/>')
    lines.append("</ResourceDictionary>")
    (OUT / f"Colors.{theme_name}.xaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def typography_xaml():
    lines = ['<!-- Generated by generate.py from tokens. Do not edit by hand. -->',
             f'<ResourceDictionary {NS_SYS}>']
    for k, v in light["font"].items():
        if k.startswith("_"):
            continue
        # WPF font lists take real family names only; CSS generics like sans-serif are not valid here.
        names = [n.strip() for n in v.split(",") if n.strip() not in ("sans-serif", "monospace", "serif")]
        lines.append(f'  <FontFamily x:Key="Font.{pascal(k)}">{html.escape(", ".join(names))}</FontFamily>')
    lines.append("")
    for k, t in light["type"].items():
        key = pascal(k)
        lines.append(f'  <sys:Double x:Key="FontSize.{key}">{t["size"]}</sys:Double>')
        lines.append(f'  <sys:Double x:Key="LineHeight.{key}">{t["line"]}</sys:Double>')
        lines.append(f'  <FontWeight x:Key="FontWeight.{key}">{WEIGHTS.get(t["weight"], "Normal")}</FontWeight>')
    lines.append("</ResourceDictionary>")
    (OUT / "Typography.xaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def metrics_xaml():
    m = light["metrics"]
    lines = ['<!-- Generated by generate.py from tokens. Do not edit by hand. -->',
             f'<ResourceDictionary {NS_SYS}>']
    for s in light["space"]:
        lines.append(f'  <sys:Double x:Key="Space.{s}">{s}</sys:Double>')
    lines.append("")
    for k, v in light["radius"].items():
        if k.startswith("_"):
            continue
        lines.append(f'  <CornerRadius x:Key="Radius.{pascal(k)}">{v}</CornerRadius>')
    lines.append("")
    w = m["window"]
    for k, v in w.items():
        lines.append(f'  <sys:Double x:Key="Window.{pascal(k.replace("_", "-"))}">{v}</sys:Double>')
    for k, v in m["search_row"].items():
        lines.append(f'  <sys:Double x:Key="SearchRow.{pascal(k.replace("_", "-"))}">{v}</sys:Double>')
    for k, v in m["settings_window"].items():
        lines.append(f'  <sys:Double x:Key="SettingsWindow.{pascal(k)}">{v}</sys:Double>')
    lines.append(f'  <sys:Double x:Key="HitTargetMin">{m["hit_target_min"]}</sys:Double>')
    lines.append(f'  <sys:Double x:Key="FocusRing.Width">{m["focus_ring"]["width"]}</sys:Double>')
    lines.append(f'  <sys:Double x:Key="FocusRing.Offset">{m["focus_ring"]["offset"]}</sys:Double>')
    lines.append(f'  <sys:Double x:Key="Icon.Size">{m["icon"]["size"]}</sys:Double>')
    lines.append(f'  <sys:Double x:Key="Icon.Stroke">{m["icon"]["stroke"]}</sys:Double>')
    mo = light["motion"]
    lines.append(f'  <Duration x:Key="Motion.Fast">0:0:0.{int(mo["fast"][:-2]):03d}</Duration>')
    lines.append(f'  <Duration x:Key="Motion.Base">0:0:0.{int(mo["base"][:-2]):03d}</Duration>')
    lines.append("</ResourceDictionary>")
    (OUT / "Metrics.xaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def css_vars(colors):
    return ";".join(f"--{k}:{v}" for k, v in colors.items())


def swatches(colors):
    cells = []
    for role, value in colors.items():
        if role == "border":
            note = "decorative, no minimum"
        elif role == "on-accent":
            note = f'{ratio(value, colors["accent"]):.1f}:1 on accent'
        elif role in ("bg", "surface", "surface-hover", "accent-subtle"):
            note = f'{ratio(colors["text"], value):.1f}:1 text on it'
        else:
            note = f'{ratio(value, colors["bg"]):.1f}:1 vs bg'
        cells.append(
            f'<div class="sw"><span class="chip" style="background:{value}"></span>'
            f'<b>{role}</b><code>{value}</code><small>{note}</small></div>')
    return "".join(cells)


